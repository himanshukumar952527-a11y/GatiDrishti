import os
from datetime import datetime, timezone

from dotenv import load_dotenv
from supabase import create_client, Client


# SUPABASE CONFIGURATION

load_dotenv()

SUPABASE_URL = os.getenv("SUPABASE_URL")
SUPABASE_SERVICE_ROLE_API_KEY = os.getenv("SUPABASE_KEY")

if not SUPABASE_URL:
    raise ValueError("SUPABASE_URL is missing from .env")

if not SUPABASE_SERVICE_ROLE_API_KEY:
    raise ValueError("SUPABASE_KEY is missing from .env")


supabase: Client = create_client(
    SUPABASE_URL,
    SUPABASE_SERVICE_ROLE_API_KEY
)


# UTC TIMESTAMP HELPER
def get_current_utc_timestamp():
    """
    Return the current UTC timestamp in ISO-8601 format.
    """
    return datetime.now(timezone.utc).isoformat()


# INSERT PREDICTION

def insert_prediction(
    running_id,
    predicted_arrival_time,
    predicted_delay,
    model_version=1,
    prediction_time=None,
    predicted_delay_change=None
):
    """
    Store a prediction in:

        ml.ml_predictions

    Parameters
    ----------
    running_id:
        ID of the operational running record.

    predicted_arrival_time:
        Predicted arrival time / ETA at the next station.

    predicted_delay:
        Final predicted delay in minutes.

    model_version:
        Model version. Default is 1.

    prediction_time:
        Time at which the prediction was generated.
        If None, current UTC timestamp is used.

    predicted_delay_change:
        Raw model output representing the predicted
        change in delay.

    Notes
    -----
    prediction_id is not inserted manually.
    It must be auto-generated by the database.
    """

    # Automatically generate timestamp if not provided
    if prediction_time is None:
        prediction_time = get_current_utc_timestamp()

    # Required prediction data
    data = {
        "running_id": running_id,
        "prediction_time": prediction_time,
        "predicted_arrival_time": predicted_arrival_time,
        "predicted_delay": predicted_delay,
        "model_version": model_version
    }

    # Add optional field only when a value is available
    if predicted_delay_change is not None:
        data["predicted_delay_change"] = (
            predicted_delay_change
        )

    # Insert into ML schema
    response = (
        supabase
        .schema("ml")
        .table("ml_predictions")
        .insert(data)
        .execute()
    )

    return response.data


# SAFE INSERT

def safe_insert_prediction(
    **kwargs
):
    """
    Safely insert a prediction.

    Returns
    -------
    Success:
    {
        "success": True,
        "data": [...]
    }

    Failure:
    {
        "success": False,
        "error_type": "...",
        "error": "..."
    }
    """

    try:
        result = insert_prediction(
            **kwargs
        )

        return {
            "success": True,
            "data": result
        }

    except Exception as error:

        return {
            "success": False,
            "error_type": type(error).__name__,
            "error": str(error)
        }


